"""Generate the screen's Chinese QFF subset with QMK's font converter."""

import argparse
import io
import logging
from pathlib import Path

from qmk.painter import valid_formats
from qmk.painter_qff import QFFFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="NotoSansCJKsc-Regular.otf from Noto CJK Sans 2.004")
    args = parser.parse_args()

    board = Path(__file__).resolve().parent / "reference"
    dashboard = (board / "dashboard.c").read_text(encoding="utf-8")
    glyphs = "".join(sorted({char for char in dashboard if "\u4e00" <= char <= "\u9fff"}))
    font = QFFFont(logging.getLogger(__name__))
    font.generate_image(args.font, 16, unicode_glyphs=glyphs)
    if not 0 < font.glyph_height <= 22:
        raise ValueError(f"Screen text strips require a font at most 22 px high, got {font.glyph_height}")
    output = io.BytesIO()
    font.save_to_qff(valid_formats["mono2"], True, output)
    data = output.getvalue()
    if not data:
        raise ValueError("Font conversion produced no data")

    out_dir = board / "fonts"
    out_dir.mkdir(exist_ok=True)
    (out_dir / "ak650_sc_16.qff.h").write_text(
        "// SPDX-License-Identifier: OFL-1.1\n#pragma once\n#include <stdint.h>\n\n"
        "extern const uint8_t font_ak650_sc_16[];\n", encoding="ascii"
    )
    lines = [", ".join(f"0x{value:02x}" for value in data[i:i + 16]) for i in range(0, len(data), 16)]
    source = (
        "// SPDX-License-Identifier: OFL-1.1\n"
        "// Glyphs from Noto Sans CJK SC. See OFL.txt.\n"
        "// Generated by generate_screen_font.py.\n"
        '#include "ak650_sc_16.qff.h"\n\n'
        "const uint8_t font_ak650_sc_16[] = {\n"
        + "".join(f"    {line},\n" for line in lines) + "};\n"
    )
    (out_dir / "ak650_sc_16.qff.c").write_text(source, encoding="ascii")
    tiny = QFFFont(logging.getLogger(__name__))
    tiny.generate_image(args.font, 10)
    packed = io.BytesIO(); tiny.save_to_qff(valid_formats["mono2"], True, packed)
    data = packed.getvalue()
    (out_dir / "online_ascii_10.qff.h").write_text("// SPDX-License-Identifier: OFL-1.1\n#pragma once\n#include <stdint.h>\nextern const uint8_t font_online_ascii_10[];\n", encoding="ascii")
    source = '// SPDX-License-Identifier: OFL-1.1\n// Noto Sans CJK SC; see OFL.txt.\n#include "online_ascii_10.qff.h"\nconst uint8_t font_online_ascii_10[] = {\n'
    source += "".join("    " + ", ".join(f"0x{v:02x}" for v in data[i:i+16]) + ",\n" for i in range(0,len(data),16)) + "};\n"
    (out_dir / "online_ascii_10.qff.c").write_text(source, encoding="ascii")
    print(f"Generated {len(glyphs)} CJK glyphs, {font.glyph_height} px high, {len(data)} bytes.")


if __name__ == "__main__":
    main()
